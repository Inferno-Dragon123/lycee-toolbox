function p(text) {
  return new Paragraph({
    spacing: { before: 80, after: 80, line: 380 },
    indent: { firstLine: 480 },
    alignment: AlignmentType.BOTH,
    children: [new TextRun({ text, size: 24, font: "SimSun" })]
  });
}
function pSmall(text, italics = false) {
  return new Paragraph({
    spacing: { before: 60, after: 60, line: 320 },
    alignment: AlignmentType.BOTH,
    children: [new TextRun({ text, size: 20, font: "SimSun", italics })]
  });
}
function pCenter(text, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 100, after: 60 },
    children: [new TextRun({ text, size: 22, font: "SimSun", bold: true, ...opts })]
  });
}
function blank() {
  return new Paragraph({ spacing: { before: 60, after: 60 }, children: [new TextRun("")] });
}
function formula(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 100, after: 100 },
    children: [new TextRun({ text, size: 22, font: "Cambria Math", italics: true })]
  });
}

// ─── Table builder ────────────────────────────────────────────
function makeTable(colWidths, headerRow, dataRows, note) {
  const totalW = colWidths.reduce((a, b) => a + b, 0);
  const makeHeaderCell = (text) => (w) => new TableCell({
    borders,
    shading: { fill: "1F3864", type: ShadingType.CLEAR },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    width: { size: w, type: WidthType.DXA },
    children: [new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text, bold: true, size: 20, color: "FFFFFF", font: "SimSun" })]
    })]
  });
  const makeDataCell = (text, shade, bold = false, align = AlignmentType.CENTER) => (w) => new TableCell({
    borders,
    shading: shade ? { fill: shade, type: ShadingType.CLEAR } : undefined,
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    width: { size: w, type: WidthType.DXA },
    children: [new Paragraph({
      alignment: align,
      children: [new TextRun({ text, size: 20, font: "SimSun", bold })]
    })]
  });

  const rows = [
    new TableRow({
      tableHeader: true,
      children: headerRow.map((t, i) => makeHeaderCell(t)(colWidths[i]))
    }),
    ...dataRows.map((row, ri) =>
      new TableRow({
        children: row.map((cell, ci) => {
          const shade = ri % 2 === 0 ? "EBF3FB" : null;
          const bold = ci === 0;
          return makeDataCell(cell, shade, bold)(colWidths[ci]);
        })
      })
    )
  ];

  const tableEl = new Table({
    width: { size: totalW, type: WidthType.DXA },
    columnWidths: colWidths,
    rows
  });

  return [tableEl, pSmall(note, true)];
}

